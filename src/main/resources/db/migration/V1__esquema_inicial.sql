-- incluyendo los CHECK constraints actualizados a mano.

CREATE TABLE public.clientes (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    direccion character varying(200),
    fecha_registro date NOT NULL,
    nombre_completo character varying(100) NOT NULL,
    numero_documento character varying(20) NOT NULL,
    telefono character varying(20),
    CONSTRAINT clientes_pkey PRIMARY KEY (id),
    CONSTRAINT uk2viccgf178bd74vfbq8ctsv8t UNIQUE (numero_documento)
);

CREATE TABLE public.creditos (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    cuota_mensual numeric(12,2) NOT NULL,
    estado character varying(20) NOT NULL,
    fecha_inicio date NOT NULL,
    monto_solicitado numeric(12,2) NOT NULL,
    plazo_meses integer NOT NULL,
    tasa_interes_mensual numeric(5,2) NOT NULL,
    cliente_id bigint NOT NULL,
    CONSTRAINT creditos_pkey PRIMARY KEY (id),
    CONSTRAINT creditos_estado_check CHECK (estado IN
        ('PENDIENTE', 'APROBADO', 'RECHAZADO', 'PAGADO', 'EN_MORA')),
    CONSTRAINT fkebytgljwj03rs91cbtjvc3cdk FOREIGN KEY (cliente_id) REFERENCES public.clientes(id)
);

CREATE TABLE public.pagos (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    estado character varying(20) NOT NULL,
    fecha_pago date NOT NULL,
    fecha_vencimiento date NOT NULL,
    monto_pagado numeric(12,2) NOT NULL,
    numero_cuota integer NOT NULL,
    credito_id bigint NOT NULL,
    CONSTRAINT pagos_pkey PRIMARY KEY (id),
    CONSTRAINT pagos_estado_check CHECK (estado IN ('PENDIENTE', 'PAGADO', 'ATRASADO')),
    CONSTRAINT fk44ifjboo8mdm0we5nlobr2pxb FOREIGN KEY (credito_id) REFERENCES public.creditos(id)
);

CREATE TABLE public.usuarios (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    nombre_usuario character varying(50) NOT NULL,
    password character varying(255) NOT NULL,
    rol character varying(20) NOT NULL,
    activo boolean DEFAULT true NOT NULL,
    CONSTRAINT usuarios_pkey PRIMARY KEY (id),
    CONSTRAINT ukof5vabgukahdwmgxk4kjrbu98 UNIQUE (nombre_usuario)
);

CREATE TABLE public.auditoria (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    accion character varying(255) NOT NULL,
    detalle character varying(500),
    entidad character varying(255) NOT NULL,
    entidad_id bigint,
    fecha timestamp(6) without time zone NOT NULL,
    usuario character varying(255) NOT NULL,
    CONSTRAINT auditoria_pkey PRIMARY KEY (id),
    CONSTRAINT auditoria_accion_check CHECK (accion IN (
        'CREDITO_APROBADO', 'CREDITO_RECHAZADO', 'CREDITO_EN_MORA', 'CREDITO_PAGADO',
        'PAGO_REGISTRADO', 'USUARIO_CREADO', 'USUARIO_ACTIVADO', 'USUARIO_DESACTIVADO',
        'CREDITO_AL_DIA', 'CREDITO_ELIMINADO', 'CLIENTE_ELIMINADO', 'CREDITO_CREADO',
        'CLIENTE_CREADO', 'CLIENTE_EDITADO', 'LOGIN_EXITOSO', 'LOGIN_FALLIDO'))
);

CREATE TABLE public.notificaciones (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    credito_id bigint,
    fecha timestamp(6) without time zone NOT NULL,
    leida boolean NOT NULL,
    mensaje character varying(500) NOT NULL,
    tipo character varying(50) NOT NULL,
    numero_cuota integer,
    CONSTRAINT notificaciones_pkey PRIMARY KEY (id),
    CONSTRAINT notificaciones_tipo_check CHECK (tipo IN ('CREDITO_EN_MORA', 'CUOTA_PROXIMA_A_VENCER'))
);
