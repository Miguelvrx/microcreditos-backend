-- V3: interés moratorio.
-- Registra los cobros y las condonaciones de mora de cada crédito. El interés devengado NO se
-- guarda: se calcula (InteresMoratorioService). El saldo de mora es devengado - cobrado - condonado.

CREATE TABLE movimientos_mora (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    credito_id bigint        NOT NULL REFERENCES creditos (id),
    tipo       varchar(20)   NOT NULL,
    monto      numeric(12,2) NOT NULL,
    fecha      date          NOT NULL,
    motivo     varchar(300),
    usuario    varchar(100)  NOT NULL,
    creado_en  timestamp(6)  NOT NULL,
    CONSTRAINT movimientos_mora_tipo_check  CHECK (tipo IN ('COBRO', 'CONDONACION')),
    CONSTRAINT movimientos_mora_monto_check CHECK (monto > 0),
    -- Una condonación siempre lleva motivo.
    CONSTRAINT movimientos_mora_motivo_check
        CHECK (tipo <> 'CONDONACION' OR (motivo IS NOT NULL AND length(btrim(motivo)) > 0))
);

CREATE INDEX idx_movimientos_mora_credito ON movimientos_mora (credito_id);

